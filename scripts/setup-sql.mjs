// The numbered SQL steps in sql/, as a module the Worker serves on /setup (for people who
// keep their notes on their own Supabase). The Worker can't read files, so this writes
// worker/src/setup-sql.mjs; tests/setup-sql.test.mjs fails when it falls behind sql/.
//   node scripts/setup-sql.mjs

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DIR = new URL('../sql/', import.meta.url);
export const OUT = new URL('../worker/src/setup-sql.mjs', import.meta.url);

export function steps() {
  return readdirSync(DIR).filter((f) => /^\d{3}_[\w-]+\.sql$/.test(f)).sort()
    .map((name) => ({ step: Number(name.slice(0, 3)), name, sql: readFileSync(new URL(name, DIR), 'utf8').replace(/\r\n/g, '\n') }));
}

export function moduleText() {
  return `// Generated by scripts/setup-sql.mjs from sql/. Don't edit: change sql/ and run it again.\n`
    + `export const SQL_STEPS = ${JSON.stringify(steps(), null, 2)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, moduleText());
  console.log(`worker/src/setup-sql.mjs: ${steps().length} steps`);
}
