// Every app icon from ONE drawing: Mullo's face (the mini from app/ui/mascot.js, idle mood:
// open eyes, smile) on the dark teal of the mascot's stand (owner, 2026-10-10).
//   node scripts/make-icons.mjs
// Writes: app/icons (web: svg + PNGs), the iPhone and Apple Watch 1024px icons, and the
// Android phone + Wear OS adaptive icons (vector XML, sharp at every size and on round faces).
// PNGs are rendered by headless Chrome (CHROME=<path> if it's not in the default place);
// no dependencies, like scripts/smoke.mjs.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const CHROME = process.env.CHROME ?? (process.platform === 'win32'
  ? 'C:/Program Files/Google/Chrome/Application/chrome.exe'
  : process.platform === 'darwin' ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' : 'chromium');

const BG = '#1A3639';
const GRAD_IN = '#FFE6EC';
const GRAD_OUT = '#E996AA';
const STEM = '#F4BCC8';
const MINT = '#9EDDCF';
const DARK = '#221628';
const CHEEK = '#EE8DA2';
const MOUTH = '#5A2338';

// The face in its own 100x100 box (art spans about x 8-92, y 6-95; centre 50, 50.5).
const BODY = 'M12 88 C8 58 24 34 50 34 C76 34 92 58 88 88 Q50 95 12 88 Z';
const STEM_PATH = 'M50 36 C46 28 56 24 52 16';
const SMILE = 'M43 73 Q50 83 57 73 Z';
const face = (grad) => `
  <path d="${STEM_PATH}" fill="none" stroke="${STEM}" stroke-width="4" stroke-linecap="round"/>
  <circle cx="53" cy="12" r="5.5" fill="${MINT}"/>
  <path d="${BODY}" fill="url(#${grad})"/>
  <circle cx="38" cy="62" r="7" fill="${DARK}"/><circle cx="36" cy="59" r="2.6" fill="#FFFFFF"/>
  <circle cx="62" cy="62" r="7" fill="${DARK}"/><circle cx="60" cy="59" r="2.6" fill="#FFFFFF"/>
  <ellipse cx="27" cy="72" rx="5" ry="3" fill="${CHEEK}" opacity="0.7"/>
  <ellipse cx="73" cy="72" rx="5" ry="3" fill="${CHEEK}" opacity="0.7"/>
  <path d="${SMILE}" fill="${MOUTH}"/>`;

// art = how much of the square the face's 100-unit box takes; rx = rounded corners (0 = square,
// for platforms that round or crop it themselves: iOS, watchOS, Android maskable).
function svg({ art, rx = 0 }) {
  const s = (512 * art) / 100 / 100; // px per face unit: art% of 512, over the face's 100 units
  const tx = 256 - 50 * s;
  const ty = 256 - 50.5 * s;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <defs><radialGradient id="g" cx="0.4" cy="0.35" r="0.75"><stop offset="0" stop-color="${GRAD_IN}"/><stop offset="1" stop-color="${GRAD_OUT}"/></radialGradient></defs>
  <rect width="512" height="512" rx="${rx}" fill="${BG}"/>
  <g transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)}) scale(${s.toFixed(4)})">${face('g')}
  </g>
</svg>
`;
}

const tmp = mkdtempSync(join(tmpdir(), 'mullo-icons-'));
function png(markup, size, out) {
  const page = join(tmp, 'icon.html');
  writeFileSync(page, `<!doctype html><html><body style="margin:0;background:transparent">${
    markup.replace('<svg ', `<svg width="${size}" height="${size}" `)}</body></html>`);
  execFileSync(CHROME, ['--headless', '--disable-gpu', '--hide-scrollbars', '--force-device-scale-factor=1',
    '--default-background-color=00000000', `--window-size=${size},${size}`, `--screenshot=${out}`, `file://${page}`],
  { stdio: 'ignore' });
}

const root = new URL('..', import.meta.url).pathname;
const at = (p) => join(root, p);

// Web: a rounded SVG, square PNGs (headless Chrome screenshots have no transparency, so rounded
// corners would come out white; the system rounds them), and a maskable one with the face in
// the 80% safe zone.
writeFileSync(at('app/icons/icon.svg'), svg({ art: 74, rx: 112 }));
png(svg({ art: 74 }), 192, at('app/icons/icon-192.png'));
png(svg({ art: 74 }), 512, at('app/icons/icon-512.png'));
png(svg({ art: 62 }), 512, at('app/icons/icon-maskable-512.png'));

// iPhone: square and opaque (iOS rounds it). Apple Watch: cropped to a circle, so the face
// stays well inside it.
png(svg({ art: 74 }), 1024, at('ios/Mullo/Assets.xcassets/AppIcon.appiconset/icon-1024.png'));
png(svg({ art: 64 }), 1024, at('ios/MulloWatch/Assets.xcassets/AppIcon.appiconset/icon-1024.png'));

// Android phone + Wear OS: adaptive icon = background colour + vector foreground. The
// foreground is 108dp; launchers show the middle 72dp and may crop to a 66dp circle, so the
// face (about 88 units tall) is scaled to about 60dp.
const S = 0.68;
const foreground = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-icons.mjs: Mullo's face, idle mood. Edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="${(54 - 50 * S).toFixed(2)}" android:translateY="${(54 - 50.5 * S).toFixed(2)}"
        android:scaleX="${S}" android:scaleY="${S}">
        <path android:pathData="${STEM_PATH}" android:strokeColor="${STEM}" android:strokeWidth="4" android:strokeLineCap="round"/>
        <path android:pathData="M47.5,12 a5.5,5.5 0 1,0 11,0 a5.5,5.5 0 1,0 -11,0" android:fillColor="${MINT}"/>
        <path android:pathData="${BODY}">
            <aapt:attr name="android:fillColor">
                <gradient android:type="radial" android:centerX="42" android:centerY="54.6"
                    android:gradientRadius="56" android:startColor="${GRAD_IN}" android:endColor="${GRAD_OUT}"/>
            </aapt:attr>
        </path>
        <path android:pathData="M31,62 a7,7 0 1,0 14,0 a7,7 0 1,0 -14,0" android:fillColor="${DARK}"/>
        <path android:pathData="M33.4,59 a2.6,2.6 0 1,0 5.2,0 a2.6,2.6 0 1,0 -5.2,0" android:fillColor="#FFFFFF"/>
        <path android:pathData="M55,62 a7,7 0 1,0 14,0 a7,7 0 1,0 -14,0" android:fillColor="${DARK}"/>
        <path android:pathData="M57.4,59 a2.6,2.6 0 1,0 5.2,0 a2.6,2.6 0 1,0 -5.2,0" android:fillColor="#FFFFFF"/>
        <path android:pathData="M22,72 a5,3 0 1,0 10,0 a5,3 0 1,0 -10,0" android:fillColor="${CHEEK}" android:fillAlpha="0.7"/>
        <path android:pathData="M68,72 a5,3 0 1,0 10,0 a5,3 0 1,0 -10,0" android:fillColor="${CHEEK}" android:fillAlpha="0.7"/>
        <path android:pathData="${SMILE}" android:fillColor="${MOUTH}"/>
    </group>
</vector>
`;
const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-icons.mjs. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
`;
const colour = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-icons.mjs. -->
<resources>
    <color name="ic_launcher_background">${BG}</color>
</resources>
`;
for (const mod of ['app', 'wear']) {
  const res = at(`android/${mod}/src/main/res`);
  for (const dir of ['drawable', 'mipmap-anydpi', 'values']) mkdirSync(join(res, dir), { recursive: true });
  writeFileSync(join(res, 'drawable/ic_launcher_foreground.xml'), foreground);
  writeFileSync(join(res, 'mipmap-anydpi/ic_launcher.xml'), adaptive);
  writeFileSync(join(res, 'values/ic_launcher_colors.xml'), colour);
}

rmSync(tmp, { recursive: true, force: true });
console.log('icons written: app/icons, ios (phone + watch), android (phone + wear)');
